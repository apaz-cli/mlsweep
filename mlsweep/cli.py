        "\n"
        "help:\n"
        '\t@echo "mlsweep targets:"\n'
        f"{help_block}\n"
        "\n"
        "sweep-manager:\n"
        "\tmlsweep manager\n"
        "\n"
        "sweep-status:\n"
        "\tmlsweep status\n"
        "\n"
        "sweep-docs:\n"
